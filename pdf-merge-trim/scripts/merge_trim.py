def _is_cropbox_grid(page, ratio=0.9):
    """
    ??????????? + CropBox ??????? A4 ??????????
    CropBox ???? MediaBox ??????????????????
    """
    mb = page.mediabox
    cb = page.cropbox
    return cb.width < mb.width * ratio or cb.height < mb.height * ratio


def _is_image_format(page, bbox, coverage_threshold=0.95):
    """
    ??????????? + ????????????
    ?bbox ????????????? >= 95%??
    ?????????????????? FBA ??????????
    """
    if _page_has_text(page):
        return False
    pw, ph = page.rect.width, page.rect.height
    if pw <= 0 or ph <= 0 or bbox is None:
        return False
    coverage = (bbox.width * bbox.height) / (pw * ph)
    return coverage >= coverage_threshold


def _page_handling(page, target_w, target_h, no_trim, preserve_native,
                   margin_pct, dpi, threshold, ratio_threshold=0.90,
                   image_coverage=0.95):
    """
    ?????????
      "copy"  ? ????????????????????????
      "grid"  ? ??? + CropBox ?????????????????
                ?????????????????????????
      "trim"  ? ????? bbox ????????????
      "image" ? ???????????????????? ? ???????
                ??????? FBA ??
    """
    # ????????????????????????????????
    if _is_cropbox_grid(page):
        return "grid"

    native = abs(page.rect.width - target_w) < 1 and abs(page.rect.height - target_h) < 1
    if native and (no_trim or preserve_native):
        # ??????????????????/????????????
        return "copy"

    bbox = detect_content_bbox(
        page, dpi=dpi, threshold=threshold, margin_pct=margin_pct, region=page.rect
    )
    # ???????????????????? ? ???????????? FBA ??
    if _is_image_format(page, bbox, coverage_threshold=image_coverage):
        return "image"

    if not native:
        return "trim"
    if no_trim:
        return "copy"
    # ????preserve_native=False????????????? ? ???????
    if bbox and bbox.width > 0 and bbox.height > 0:
        content_ratio = (bbox.width * bbox.height) / (page.rect.width * page.rect.height)
        if content_ratio < ratio_threshold:
            return "trim"
    return "copy"


