def find_pdf_files(source_dir, keyword=None, max_size_mb=200, exclude_filenames=None):
    """
    ???? source_dir ??? PDF ???
    ??
    ----
    source_dir        : str  ?????
    keyword           : str  ?????????????????None ?????
    max_size_mb       : int  ????????MB?????0 ?????
    exclude_filenames : set[str]  ????????????????????????????

    ??
    ----
    list[str]  ??????? PDF ??????
    """
    excluded = set(exclude_filenames) if exclude_filenames else set()
    results = []
    for root, _dirs, fns in os.walk(source_dir):
        for fn in sorted(fns):
            if not fn.lower().endswith(".pdf"):
                continue
            # ???????????????????
            if fn in excluded:
                continue
            if any(frag in fn for frag in _EXCLUDE_FRAGMENTS):
                continue
            # ?????
            if keyword and keyword.upper() not in fn.upper():
                continue
            fp = os.path.join(root, fn)
            # ??????
            if max_size_mb > 0 and os.path.getsize(fp) > max_size_mb * 1024 * 1024:
                print("  [??] ???? (>{} MB): {}".format(max_size_mb, fn))
                continue
            results.append(fp)
    return results


