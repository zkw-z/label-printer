def _add_hidden_fba_text_pdf(page_obj, fba_number, page_w, page_h, pdf,
                             font_size=10, bottom_mm=10):
    """
    pikepdf ?????????? PDF ??????? FBA ???????? 3??
    ???? Helvetica ?????????????????/?????
    """
    MM_TO_PT = 72 / 25.4
    bottom_pt = bottom_mm * MM_TO_PT

    res = page_obj.get("/Resources", None)
    if res is None:
        res = pikepdf.Dictionary()
        page_obj["/Resources"] = res
    fonts = res.get("/Font", None)
    if fonts is None:
        fonts = pikepdf.Dictionary()
        res["/Font"] = fonts
    if "/Helv" not in fonts:
        fonts["/Helv"] = pikepdf.Dictionary(
            {
                "/Type": pikepdf.Name("/Font"),
                "/Subtype": pikepdf.Name("/Type1"),
                "/BaseFont": pikepdf.Name("/Helvetica"),
            }
        )

    text_width = fitz.get_text_length(fba_number, fontname="helv", fontsize=font_size)
    x = (page_w - text_width) / 2
    y = bottom_pt  # PDF ?? y ?????? bottom_mm

    stream = b"q BT /Helv %f Tf %f %f Td 3 Tr (%s) Tj ET Q" % (
        font_size,
        x,
        y,
        fba_number.encode("latin-1"),
    )
    new_content = pikepdf.Stream(pdf, stream)
    contents = page_obj.get("/Contents", None)
    if contents is None:
        page_obj["/Contents"] = new_content
    elif isinstance(contents, pikepdf.Array):
        contents.append(new_content)
    else:
        page_obj["/Contents"] = pikepdf.Array([contents, new_content])


