def _fitz_bbox_to_pdf_rect(page, bbox):
    """
    fitz ?????y ????? CropBox ???? PDF ?????y ????? MediaBox??
    Y ????? CropBox ??? PDF y ??????????
        flip_base = mediabox.y1 - cropbox.y0
    ?? mediabox/cropbox ?? fitz ??? y ??????? MediaBox ?????
    ?? CropBox?y0 != 0????????????????????????
    """
    mb = page.mediabox
    cb = page.cropbox
    flip_base = mb.y1 - cb.y0  # CropBox ???PDF y ???
    return fitz.Rect(
        cb.x0 + bbox.x0,
        flip_base - bbox.y1,
        cb.x0 + bbox.x1,
        flip_base - bbox.y0,
    )


def _build_binary_page(out, spage, pdf_rect, target_w, target_h):
    """
    ???????????? CropBox ? as_form_xobject ? copy_foreign ??? PDF?
    ????????/??????????? cm ???????????????????
    ???? PDF ???????
    """
    old_cb = spage.get("/CropBox", None)
    spage.CropBox = pikepdf.Array([pdf_rect.x0, pdf_rect.y0, pdf_rect.x1, pdf_rect.y1])
    try:
        form = out.copy_foreign(spage.as_form_xobject(handle_transformations=True))
    finally:
        if old_cb is None:
            del spage["/CropBox"]
        else:
            spage.CropBox = old_cb

    b = form.get("/BBox")
    bw = float(b[2] - b[0])
    bh = float(b[3] - b[1])
    if bw <= 0 or bh <= 0:
        raise ValueError("????? BBox ??: {}x{}".format(bw, bh))

    scale = min(target_w / bw, target_h / bh)
    tx = (target_w - bw * scale) / 2 - float(b[0]) * scale
    ty = (target_h - bh * scale) / 2 - float(b[1]) * scale

    np_ = out.add_blank_page(page_size=(target_w, target_h))
    np_.Resources = pikepdf.Dictionary({"/XObject": pikepdf.Dictionary({"/Fm0": form})})
    np_.Contents = pikepdf.Stream(
        out,
        b"q 0 0 %f %f re W n %f 0 0 %f %f %f cm /Fm0 Do Q"
        % (target_w, target_h, scale, scale, tx, ty),
    )
    return np_


def _process_with_pikepdf(fp, src_doc, handlings, crop_rects, target_w, target_h,
                          add_fba_text, fba_number, fba_font_size, fba_bottom_mm):
    """pikepdf ??????copy/image ????????grid/trim ??????"""
    out = pikepdf.Pdf.new()
    src2 = pikepdf.Pdf.open(fp)
    try:
        for page_idx, handling in enumerate(handlings):
            src_page = src_doc[page_idx]
            if handling in ("copy", "image"):
                out.pages.append(src2.pages[page_idx])
                new_page = out.pages[-1]
            else:
                pdf_rect = _fitz_bbox_to_pdf_rect(src_page, crop_rects[page_idx])
                _build_binary_page(out, src2.pages[page_idx], pdf_rect, target_w, target_h)
                new_page = out.pages[-1]

            if add_fba_text and fba_number and not _page_has_text(src_page):
                if handling in ("copy", "image"):
                    mb = new_page.get("/MediaBox")
                    pw = float(mb[2] - mb[0])
                    ph = float(mb[3] - mb[1])
                else:
                    pw, ph = target_w, target_h
                _add_hidden_fba_text_pdf(
                    new_page, fba_number, pw, ph, out,
                    font_size=fba_font_size, bottom_mm=fba_bottom_mm,
                )
    finally:
        src2.close()

    fd, tmp_path = tempfile.mkstemp(suffix="_wb_tmp.pdf")
    os.close(fd)
    out.save(tmp_path, compress_streams=False)
    out.close()
    return tmp_path


def _process_with_fitz(fp, src_doc, handlings, crop_rects, target_w, target_h,
                       add_fba_text, fba_number, fba_font_size, fba_bottom_mm):
    """
    ?????pikepdf ??????? fitz show_pdf_page ???
    ??????????????????
    """
    tmp_doc = fitz.open()
    for page_idx, handling in enumerate(handlings):
        page = src_doc[page_idx]

        if handling in ("copy", "image"):
            # ??????????????????????????????? FBA ??
            tmp_doc.insert_pdf(src_doc, from_page=page_idx, to_page=page_idx)
            new_page = tmp_doc[tmp_doc.page_count - 1]
        elif handling == "grid":
            cb = page.cropbox
            cw, ch = cb.width, cb.height
            scale = min(target_w / cw, target_h / ch)
            sw, sh = cw * scale, ch * scale
            ox = (target_w - sw) / 2
            oy = (target_h - sh) / 2
            new_page = tmp_doc.new_page(width=target_w, height=target_h)
            clip_rect = fitz.Rect(ox, oy, ox + sw, oy + sh)
            grid_clip = fitz.Rect(0, 0, cw, ch)
            new_page.show_pdf_page(clip_rect, src_doc, page_idx, clip=grid_clip)
        else:
            crop_rect = crop_rects[page_idx]
            cw, ch = crop_rect.width, crop_rect.height
            if cw <= 0 or ch <= 0:
                crop_rect = page.rect
                cw, ch = crop_rect.width, crop_rect.height
            scale = min(target_w / cw, target_h / ch)
            sw, sh = cw * scale, ch * scale
            ox = (target_w - sw) / 2
            oy = (target_h - sh) / 2
            new_page = tmp_doc.new_page(width=target_w, height=target_h)
            clip_rect = fitz.Rect(ox, oy, ox + sw, oy + sh)
            new_page.show_pdf_page(clip_rect, src_doc, page_idx, clip=crop_rect)

        if add_fba_text and fba_number and not _page_has_text(page):
            if handling in ("copy", "image"):
                tw, th = new_page.rect.width, new_page.rect.height
            else:
                tw, th = target_w, target_h
            _add_hidden_fba_text(
                new_page, fba_number, tw, th,
                font_size=fba_font_size, bottom_mm=fba_bottom_mm,
            )

    fd, tmp_path = tempfile.mkstemp(suffix="_wb_tmp.pdf")
    os.close(fd)
    tmp_doc.save(tmp_path, garbage=2, deflate=True)
    tmp_doc.close()
    return tmp_path


def process_file(
    fp,
    target_w,
    target_h,
    no_trim=False,
    dpi=150,
    threshold=240,
    margin_pct=0.01,
    native_size_threshold_mm=1.0,
    add_fba_text=False,
    fba_number=None,
    fba_font_size=10,
    fba_bottom_mm=10,
    preserve_native=True,
    image_coverage=0.95,
):
    """
    ???? PDF ???
    - ??????????preserve_native=True????? ???????????
      ?????????/????????
    - ??? + CropBox ???? ? ?????????????????????
      ????????????
    - ???????? ? ????? bbox ?????????????
    - ??????????????????????? ???????
      ??????? FBA ?????? 10mm??
    - no_trim=True ? ?????????????

    ?? (tmp_path, page_count, was_modified)
    was_modified=False ?????????True ???????
    """
    src_doc = fitz.open(fp)
    page_count = src_doc.page_count
    if page_count == 0:
        src_doc.close()
        return fp, 0, False

    # ???????????? FBA ???????????????
    need_fba = add_fba_text and fba_number and any(
        not _page_has_text(src_doc[i]) for i in range(page_count)
    )

    handlings = [
        _page_handling(
            src_doc[i], target_w, target_h, no_trim, preserve_native,
            margin_pct, dpi, threshold, image_coverage=image_coverage,
        )
        for i in range(page_count)
    ]

    if all(h == "copy" for h in handlings) and not need_fba:
        # ???????? ? ???????????????
        src_doc.close()
        return fp, page_count, False

    # ???????fitz ?????y ???
    crop_rects = []
    for i, handling in enumerate(handlings):
        if handling in ("grid", "trim"):
            page = src_doc[i]
            region = page.rect  # grid ??????
            if no_trim:
                bbox = region
            else:
                bbox = detect_content_bbox(
                    page, dpi=dpi, threshold=threshold,
                    margin_pct=margin_pct, region=region,
                )
            if bbox is None or bbox.width <= 0 or bbox.height <= 0:
                bbox = region
            crop_rects.append(bbox)
        else:
            crop_rects.append(None)

    try:
        if _HAVE_PIKEPDF:
            tmp_path = _process_with_pikepdf(
                fp, src_doc, handlings, crop_rects, target_w, target_h,
                add_fba_text, fba_number, fba_font_size, fba_bottom_mm,
            )
        else:
            tmp_path = _process_with_fitz(
                fp, src_doc, handlings, crop_rects, target_w, target_h,
                add_fba_text, fba_number, fba_font_size, fba_bottom_mm,
            )
    finally:
        src_doc.close()
    return tmp_path, page_count, True


