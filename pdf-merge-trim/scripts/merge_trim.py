def merge_with_pikepdf(file_paths, output_pdf):
    """
    ? pikepdf ????????????????100% ??????????
    file_paths: list of (path, is_tmp) ? is_tmp=True ??????????
    """
    merger = pikepdf.Pdf.new()
    total = 0
    for path, is_tmp in file_paths:
        part = pikepdf.Pdf.open(path)
        merger.pages.extend(part.pages)
        total += len(part.pages)
        part.close()
        if is_tmp:
            try:
                os.remove(path)
            except OSError:
                pass

    # ???????????????????????
    tmp_out_fd, tmp_out = tempfile.mkstemp(suffix="_final_tmp.pdf")
    os.close(tmp_out_fd)
    merger.save(tmp_out, linearize=False)
    merger.close()

    if os.path.exists(output_pdf):
        os.remove(output_pdf)
    shutil.move(tmp_out, output_pdf)  # shutil.move ??????
    return total


