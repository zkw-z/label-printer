def _is_edge_line(rect, region_w, region_h):
    """
    ?? rect ?????????????????????????????????
    ????? >= ?? 95%???? <= ?? 5%?????/????
    ???????????????????????????????
    """
    if region_w <= 0 or region_h <= 0:
        return False
    wr = rect.width / region_w
    hr = rect.height / region_h
    if (wr >= 0.95 and hr <= 0.05) or (hr >= 0.95 and wr <= 0.05):
        return True
    return False


def _bbox_from_vector(page, threshold_gray=240, margin_pct=0.01, clamp=True, region=None):
    """
    ?? A??? fitz ??????? + ???? + ??????????
    ???????? PDF ?????
    region     : fitz.Rect  ??????????????????????
                            ???????????????????
    clamp=True ??????????clamp=False ?????????????????
    """
    if region is None:
        region = page.rect
    rw, rh = region.width, region.height
    if rw <= 0 or rh <= 0:
        return None

    rects = []
    for b in page.get_text("blocks"):
        if b[4].strip():
            r = fitz.Rect(b[:4])
            if r.intersects(region):
                rects.append(r & region)

    for path in page.get_drawings():
        r = path.get("rect")
        if not r or not r.intersects(region):
            continue
        r = r & region
        if _is_edge_line(r, rw, rh):
            continue
        rects.append(r)

    for img in page.get_images(full=True):
        xref = img[0]
        for item in page.get_image_rects(xref):
            r = item & region
            if r.width > 0 and r.height > 0:
                rects.append(r)

    if not rects:
        return None

    x0 = min(r.x0 for r in rects)
    y0 = min(r.y0 for r in rects)
    x1 = max(r.x1 for r in rects)
    y1 = max(r.y1 for r in rects)

    x0, y0 = x0 - rw * margin_pct, y0 - rh * margin_pct
    x1, y1 = x1 + rw * margin_pct, y1 + rh * margin_pct
    if clamp:
        x0, y0 = max(region.x0, x0), max(region.y0, y0)
        x1, y1 = min(region.x1, x1), min(region.y1, y1)
    return fitz.Rect(x0, y0, x1, y1)


def _bbox_from_pixels(page, dpi=150, threshold_gray=240, margin_pct=0.01, clamp=True, region=None):
    """
    ?? B????????????????????????? / ??? PDF??
    region ????????????
    """
    try:
        mat = fitz.Matrix(dpi / 72, dpi / 72)
        pix = page.get_pixmap(matrix=mat, colorspace=fitz.csGRAY, alpha=False)
        samples = pix.samples
        w, h = pix.width, pix.height

        x_min, y_min, x_max, y_max = w - 1, h - 1, 0, 0
        found = False
        for py in range(h):
            row_start = py * w
            for px in range(w):
                if samples[row_start + px] < threshold_gray:
                    if px < x_min:
                        x_min = px
                    if py < y_min:
                        y_min = py
                    if px > x_max:
                        x_max = px
                    if py > y_max:
                        y_max = py
                    found = True

        if not found:
            return None

        mx = max(2, int(w * margin_pct))
        my = max(2, int(h * margin_pct))
        x_min = x_min - mx
        y_min = y_min - my
        x_max = x_max + mx
        y_max = y_max + my
        if clamp:
            x_min = max(0, x_min)
            y_min = max(0, y_min)
            x_max = min(w - 1, x_max)
            y_max = min(h - 1, y_max)

        scale_x = page.rect.width / w
        scale_y = page.rect.height / h
        bbox = fitz.Rect(
            x_min * scale_x,
            y_min * scale_y,
            (x_max + 1) * scale_x,
            (y_max + 1) * scale_y,
        )
        if region is not None:
            bbox = bbox & region
        return bbox
    except Exception as e:
        print("    [??] ??????: {}".format(e))
        return None


def detect_content_bbox(page, dpi=150, threshold=240, margin_pct=0.01, clamp=True, region=None):
    """
    ?????????????????
    region ???????clamp=True ??????????
    ??????? Rect?????????????????????
    """
    bbox = _bbox_from_vector(page, threshold, margin_pct, clamp, region)
    if bbox and bbox.width > 0 and bbox.height > 0:
        return bbox
    bbox = _bbox_from_pixels(page, dpi, threshold, margin_pct, clamp, region)
    if bbox and bbox.width > 0 and bbox.height > 0:
        return bbox
    if region is not None:
        return region
    return page.rect  # ???????


